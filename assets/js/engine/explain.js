function declaredSomewhere(name, c) {
  const re = new RegExp(`\\b(?:let|var|func|struct|class|enum|case|protocol|actor|typealias)\\s+${name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\b`);
  const lines = c.codeLines ?? [];
  for (let i = 0; i < lines.length; i++) if (re.test(lines[i])) return i + 1;
  return 0;
}

