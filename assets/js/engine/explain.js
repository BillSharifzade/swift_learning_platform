/**
 * Объяснение аварийного завершения. rt — результат parseRuntime().
 */
export function explainRuntime(rt) {
  if (!rt) return null;
  if (rt.kind === 'timeout') {
    return {
      title: 'Программа работает слишком долго',
      what: md('Программа не завершилась за отведённое время, и её пришлось остановить. Почти всегда причина — бесконечный цикл.'),
      why: md('Цикл ‹while› повторяется, пока его условие истинно. Если внутри ничего не меняет это условие, цикл не остановится никогда.'),
      fix: md('Найди цикл и проверь: меняется ли внутри переменная из условия (например, ‹i += 1›)? Станет ли условие когда-нибудь ложным? Сработает ли ‹break›?'),
      known: true,
    };
  }
  if (rt.kind === 'recursion') {
    return {
      title: 'Бесконечная рекурсия',
      what: md('Функция вызывала саму себя снова и снова, пока не закончилась память под вызовы (стек).'),
      why: md('Каждый вызов функции занимает немного памяти до своего завершения. Если функция вызывает себя без условия остановки, память кончается и программа падает.'),
      fix: md('Добавь условие выхода: случай, когда функция возвращает результат, не вызывая себя. И проверь, что каждый следующий вызов приближается к этому случаю.'),
      known: true,
    };
  }
  if (rt.kind === 'cast') {
    const from = rt.cast.from.replace(/\bPlayground\./g, ''), to = rt.cast.to.replace(/\bPlayground\./g, '');
    return {
      title: 'Принудительное приведение типа не удалось',
      what: md(`Через ‹as!› значение типа ‹${from}› попытались превратить в ‹${to}›, но на самом деле это не ‹${to}›.`),
      why: md('‹as!› означает «я уверена, что тут именно этот тип». Если это не так, программа падает.'),
      fix: md(`Используй безопасный вариант: ‹if let item = value as? ${to} { ... }› — блок выполнится, только если тип действительно подходит.`),
      known: true,
    };
  }
  if (rt.kind === 'exit') {
    return {
      title: 'Программа завершилась с кодом ошибки',
      what: md(`Программа сама завершила работу с кодом ${rt.code} (вызов ‹exit›).`),
      why: md('Код завершения, отличный от нуля, по соглашению означает «что-то пошло не так».'),
      fix: md('Убери вызов ‹exit(...)› — в этих задачах программа должна просто дойти до конца.'),
      known: true,
    };
  }
  if (rt.kind === 'overflow') {
    return {
      title: 'Программа аварийно остановилась',
      what: md('Swift остановил программу во время вычислений. Самая частая причина — переполнение: результат арифметической операции не поместился в тип числа.'),
      why: md('У ‹Int› огромный, но не бесконечный диапазон, а у ‹Int8›, ‹UInt› и подобных — совсем небольшой. Например, беззнаковое ‹UInt› не может уйти в минус. Swift не даёт числу незаметно «перевернуться».'),
      fix: md('Посмотри на отмеченную строку: что с чем складывается, вычитается или умножается и могут ли значения оказаться неожиданно большими или отрицательными.'),
      known: true,
    };
  }
  const message = rt.message ?? '';
  for (const [re, fn] of RUNTIME_RULES) {
    const m = re.exec(message);
    if (!m) continue;
    const r = fn(m);
    return { title: md(r.title), what: md(r.what), why: md(r.why), fix: md(r.fix), known: true };
  }
  if (message) {
    // fatalError("...") из кода ученицы или стартового кода
    return {
      title: md('Программа остановлена вызовом ‹fatalError›'),
      what: md(`Сообщение: «${message.replace(/\bPlayground\./g, '')}».`),
      why: md('‹fatalError› намеренно останавливает программу — обычно так помечают место, которое ещё не реализовано или куда выполнение попадать не должно.'),
      fix: md('Если это заготовка из стартового кода — замени её своей реализацией. Если ты поставила ‹fatalError› сама — проверь, почему выполнение дошло до этой строки.'),
      known: true,
    };
  }
  return {
    title: 'Программа аварийно завершилась',
    what: md('Во время работы произошёл сбой, и программа остановилась.'),
    why: md('Такое случается при обращении к несуществующим данным, бесконечной рекурсии или нарушении правил безопасности памяти.'),
    fix: md('Посмотри на отмеченную строку и проверь значения, с которыми она работает.'),
    known: false,
  };
}
