const md = s => String(s ?? '')
  .replace(/\[\[\[\n?([\s\S]*?)\n?\]\]\]/g, (_, code) => `\n\n\`\`\`swift\n${code}\n\`\`\`\n\n`)
  .replace(/‹([^›]*)›/g, '`$1`')
  .trim();

const TYPE_RU = {
  String: 'текст', Int: 'целое число', Double: 'дробное число', Float: 'дробное число',
  Bool: 'логическое значение ‹true›/‹false›', Character: 'один символ', Substring: 'кусочек строки',
  '()': '«ничего», пустой результат', Void: '«ничего», пустой результат', Any: 'значение любого типа',
};

function ty(t) {
  t = String(t).trim();
  if (TYPE_RU[t]) return `‹${t}› (${TYPE_RU[t]})`;
  let m;
  if ((m = /^(.+)\?$/.exec(t))) return `‹${t}› (опционал: либо ‹${m[1]}›, либо ‹nil›)`;
  if (/^\[[^:\]]+\]$/.test(t)) return `‹${t}› (массив)`;
  if (/^\[.+: .+\]$/.test(t)) return `‹${t}› (словарь)`;
  if (/->/.test(t)) return `‹${t}› (функция)`;
  return `‹${t}›`;
}

