function hasFoundation(c) {
  return (c.codeLines ?? []).some(l => /^\s*import\s+Foundation\b/.test(l));
}

function suggestName(name, c) {
  if (FOUNDATION_NAMES.has(name) && name !== 'abs' && !hasFoundation(c)) {
    return { fix: 'import Foundation', text: `‹${name}› живёт в библиотеке Foundation, а она не подключена. Добавь первой строкой файла ‹import Foundation›.`, raw: true };
  }
  if (FOREIGN[name]) return { fix: FOREIGN[name][0], text: FOREIGN[name][1] };
  const known = [...new Set([...(c.identifiers ?? []), ...COMMON_NAMES])].filter(x => x !== name);
  // 1) одинаково выглядит, но набрано в другой раскладке
  const twin = known.find(x => skeleton(x) === skeleton(name));
  if (twin) {
    return { fix: twin, text: `В коде есть ‹${twin}›, которое выглядит так же, но набрано другими буквами — часть из них русские, часть латинские. Для Swift это разные имена. Перепечатай оба в английской раскладке.` };
  }
  // 2) отличается только регистром
  const sameCase = known.find(x => x.toLowerCase() === name.toLowerCase());
  if (sameCase) {
    return { fix: sameCase, text: `Очень похоже на ‹${sameCase}› — отличие только в больших и маленьких буквах, а Swift их различает.` };
  }
  // 3) опечатка
  let best = null, bestD = 99;
  for (const k of known) {
    if (Math.abs(k.length - name.length) > 2) continue;
    const d = editDistance(k, name);
    if (d < bestD) { best = k; bestD = d; }
  }
  const limit = name.length <= 4 ? 1 : 2;
  if (best && bestD <= limit) return { fix: best, text: `Похоже на опечатку: возможно, имелось в виду ‹${best}›.` };
  return null;
}

/** Имена параметров типа, объявленных в коде: func f<T>, struct Cache<Key, Value>, associatedtype Item. */
function genericParams(c) {
  const text = (c.codeLines ?? []).join('\n');
  const out = new Set();
  const re = /\b(?:func|struct|class|enum|actor|init|subscript)\b[^\n<({]*?<([^<>]*)>/g;
  let m;
  while ((m = re.exec(text))) for (const part of m[1].split(',')) { const n = /^\s*([A-Za-z_]\w*)/.exec(part); if (n) out.add(n[1]); }
  for (const a of text.matchAll(/\bassociatedtype\s+([A-Za-z_]\w*)/g)) out.add(a[1]);
  return out;
}

