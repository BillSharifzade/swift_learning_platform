export function explainNote(note) {
  for (const [re, fn] of NOTE_RULES) {
    const m = re.exec(note.message);
    if (m) return md(fn(m, note));
  }
  return '';
}

/**
 * Объяснение одной диагностики.
 * ctx: { region, codeLines, identifiers, notes, srcLine, isParam }
 */
export function explainDiagnostic(message, ctx = {}) {
  for (const [re, fn] of RULES) {
    const m = re.exec(message);
    if (!m) continue;
    const r = fn(m, ctx);
    return { title: md(r.title), what: md(r.what), why: md(r.why), fix: md(r.fix), known: true };
  }
  const glossary = glossaryFor(message);
  return {
    title: 'Компилятор нашёл ошибку',
    what: md(`Вот что он сообщает: ‹${message.replace(/`/g, "'")}›.`),
    why: md(glossary ? `Сообщение на английском, но его можно разобрать. Словарик: ${glossary}.` : 'Это сообщение компилятора на английском — попробуй перевести его по частям.'),
    fix: md(ctx.region && ctx.region !== 'user'
      ? 'Ошибка возникла на стыке твоего кода и проверки. Сверь с условием названия, типы и параметры того, что нужно было объявить.'
      : 'Внимательно посмотри на отмеченное место и на строку перед ним: чаще всего дело в опечатке, пропущенном символе или перепутанном типе. Если не получается — открой подсказку.'),
    known: false,
  };
}

